: ABBREV-STR, ( ptr u8 n -- )
   {: a:ptr u:n :}
   u 255 > if E-STR-CAPACITY throw then
   u c,  u 0 ?do a i + c@ c, loop ;
: ABBREV, ( ptr u8 n ptr u8 n -- )
   {: kp:ptr ku:n vp:ptr vu:n :}
   kp ku ABBREV-STR, vp vu ABBREV-STR, ;
